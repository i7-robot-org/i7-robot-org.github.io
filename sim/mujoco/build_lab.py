#!/usr/bin/env python3
"""Generate i7_lab.xml: the vendor i7 MJCF (V1.5) placed in the demo lab used by the film and web viewer.

What this adds on top of vendor/robot_model/urdf_v1.5_0416/mjcf/URDF_V1.5_0416.xml:
  * a planar chassis (slide x, slide y, hinge yaw) driven by velocity actuators, so the base can move
  * gravity compensation on the robot bodies, so the arms hold their pose with zero torque command
  * the lab (real floor plan, 9.0 x 6.9 m): walls with the door, two rows of five office desks, the storage areas,
    the drawer table and a free-floating bottle
  * cameras (overview, table view, head camera on the lift) and keyframes for the start and table poses

Layout matches docs/showcase/assets/i7sim.js (map frame, metres, Z up).
Run:  python3 build_lab.py   (writes i7_lab.xml next to this file)
"""
import copy
import math
import pathlib
import xml.etree.ElementTree as ET

HERE = pathlib.Path(__file__).resolve().parent
VENDOR = HERE / "../../../../vendor/robot_model/urdf_v1.5_0416/mjcf/URDF_V1.5_0416.xml"
MESHDIR = "../../../../vendor/robot_model/urdf_v1.5_0416/meshes"

ROOM = dict(x0=-4.5, x1=4.5, y0=-3.45, y1=3.45, wall=0.08, h=1.0)
DESK = dict(w=1.4, d=1.0, h=0.75, x0=-3.5, n=5)          # two rows of five 1.4 x 1.0 m desks on the north and south walls
STORE = [(-4.5, -3.5), (3.5, 4.5)]                       # storage areas, 1.0 x 4.0 m, y from -2 to 2
DOOR = (-3.35, -2.45)                                    # door opening in the west wall (y range)
TABLE = dict(x0=0.475, x1=0.925, y0=0.0, y1=0.4, h=0.62) # drawer table, 45 x 40 x 62 cm, holds the bottle
BOTTLE = (0.66, 0.2)
BASE_TO_CENTER = 0.26                   # base_link origin sits at the front of the chassis
PERSON_X = -1.4 + 0.4 * 1.75 / 1.82     # where the person stands after getting up from the second desk in the north row
START = (PERSON_X + 1.13, 2.095, math.pi)                 # chassis centre and yaw where the command is given
AT_TABLE = (BOTTLE[0] - 0.43 - BASE_TO_CENTER, BOTTLE[1] + 0.25, 0.0)   # chassis centre squared up to the drawer table
LIFT_AT_TABLE = -0.1 - (0.75 - TABLE["h"])              # lift lowered for the 0.62 m table

f = lambda *v: " ".join(f"{x:.4f}".rstrip("0").rstrip(".") if isinstance(x, float) else str(x) for x in v)


def lookat(pos, target):
    """MuJoCo camera xyaxes (image right, image up) for a camera at pos looking at target."""
    d = [t - p for p, t in zip(pos, target)]
    n = math.sqrt(sum(v * v for v in d)); d = [v / n for v in d]
    x = [d[1], -d[0], 0.0]; n = math.hypot(x[0], x[1]); x = [v / n for v in x]
    y = [x[1] * d[2] - x[2] * d[1], x[2] * d[0] - x[0] * d[2], x[0] * d[1] - x[1] * d[0]]
    return f(*x, *y)


def sub(parent, tag, **attrs):
    return ET.SubElement(parent, tag, {k.rstrip("_"): str(v) for k, v in attrs.items()})


def box(parent, name, x0, x1, y0, y1, z0, z1, material):
    sub(parent, "geom", name=name, type="box", material=material,
        pos=f((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2), size=f((x1 - x0) / 2, (y1 - y0) / 2, (z1 - z0) / 2))


def table(parent, name, x0, x1, y0, y1, h, top="wood"):
    box(parent, f"{name}_top", x0, x1, y0, y1, h - 0.035, h, top)
    for i, (x, y) in enumerate([(x0 + 0.05, y0 + 0.05), (x1 - 0.05, y0 + 0.05), (x0 + 0.05, y1 - 0.05), (x1 - 0.05, y1 - 0.05)]):
        sub(parent, "geom", name=f"{name}_leg{i}", type="cylinder", material="metal", size=f(0.018, (h - 0.035) / 2), pos=f(x, y, (h - 0.035) / 2))


def main():
    vendor = ET.parse(VENDOR).getroot()
    root = ET.Element("mujoco", model="i7_lab")
    root.append(ET.Comment(" generated by build_lab.py from the vendor MJCF; edit the generator, not this file "))
    opt = copy.deepcopy(vendor.find("option")); opt.set("timestep", "0.002"); root.append(opt)
    sub(root, "compiler", angle="radian", meshdir=MESHDIR)
    sub(root, "statistic", center="0 -1 0.8", extent="5")
    vis = sub(root, "visual")
    sub(vis, "headlight", diffuse="0.55 0.55 0.55", ambient="0.25 0.25 0.25", specular="0 0 0")
    sub(vis, "global", azimuth="-110", elevation="-28", offwidth="1920", offheight="1080")
    sub(vis, "quality", shadowsize="4096")

    default = sub(root, "default")
    sub(default, "geom", contype="1", conaffinity="1", friction="0.9 0.02 0.001")
    robot_cls = sub(default, "default", class_="i7")
    sub(robot_cls, "geom", contype="0", conaffinity="0")   # robot meshes are visual only, as in the vendor file

    asset = copy.deepcopy(vendor.find("asset")); root.append(asset)
    sub(asset, "texture", name="floor_grid", type="2d", builtin="checker", rgb1=".95 .95 .96", rgb2=".91 .91 .93", width="512", height="512", mark="edge", markrgb=".84 .85 .88")
    sub(asset, "material", name="floor", texture="floor_grid", texuniform="true", texrepeat="2 2", reflectance="0.05")
    for name, rgba in [("wall", ".93 .93 .95 1"), ("cabinet", ".91 .92 .93 1"), ("benchtop", ".23 .23 .25 1"), ("wood", ".85 .80 .73 1"),
                       ("metal", ".56 .56 .6 1"), ("screen", ".08 .08 .1 1"), ("bottle", ".75 .88 1 0.55"), ("cap", ".04 .42 .87 1"),
                       ("shell", ".96 .96 .97 1"), ("lilac", ".79 .82 .93 1"), ("flange", ".6 .61 .64 1"), ("graphite", ".16 .17 .19 1")]:
        sub(asset, "material", name=name, rgba=rgba)

    contact = copy.deepcopy(vendor.find("contact")); root.append(contact)

    world = sub(root, "worldbody")
    sub(world, "light", name="sun", pos="-3.5 -5.5 9", dir="0.35 0.55 -0.9", directional="true", castshadow="true", diffuse="0.75 0.75 0.75")
    sub(world, "geom", name="floor", type="plane", size="0 0 0.05", material="floor")
    r, w, h = ROOM, ROOM["wall"], ROOM["h"]
    box(world, "wall_n", r["x0"] - w, r["x1"] + w, r["y1"], r["y1"] + w, 0, h, "wall")
    box(world, "wall_s", r["x0"] - w, r["x1"] + w, r["y0"] - w, r["y0"], 0, h * 0.35, "wall")
    box(world, "wall_w_s", r["x0"] - w, r["x0"], r["y0"] - w, DOOR[0], 0, h, "wall")
    box(world, "wall_w_n", r["x0"] - w, r["x0"], DOOR[1], r["y1"] + w, 0, h, "wall")
    box(world, "door", r["x0"] - w * 0.75, r["x0"] - w * 0.25, DOOR[0] + 0.06, DOOR[1] - 0.06, 0, h, "wood")
    box(world, "wall_e", r["x1"], r["x1"] + w, r["y0"], r["y1"], 0, h * 0.35, "wall")
    for row, (y0, y1, front) in enumerate([(r["y1"] - DESK["d"], r["y1"], -1), (r["y0"], r["y0"] + DESK["d"], 1)]):
        back = y1 - 0.38 if front < 0 else y0 + 0.38
        for i in range(DESK["n"]):
            x0 = DESK["x0"] + i * DESK["w"]
            table(world, f"desk{row}{i}", x0 + 0.003, x0 + DESK["w"] - 0.003, y0, y1, DESK["h"], top="wood")
            cx = x0 + DESK["w"] / 2
            box(world, f"monitor{row}{i}", cx - 0.28, cx + 0.28, back - 0.0125, back + 0.0125, DESK["h"] + 0.085, DESK["h"] + 0.415, "screen")
    for i, (x0, x1) in enumerate(STORE):
        box(world, f"storage{i}", x0, x1, -2.0, 2.0, 0, 1.5, "cabinet")
    box(world, "drawer_table", TABLE["x0"], TABLE["x1"], TABLE["y0"], TABLE["y1"], 0, TABLE["h"] - 0.025, "cabinet")
    box(world, "drawer_table_top", TABLE["x0"] - 0.005, TABLE["x1"] + 0.005, TABLE["y0"] - 0.005, TABLE["y1"] + 0.005, TABLE["h"] - 0.025, TABLE["h"], "wood")

    sub(world, "camera", name="overview", pos=f(0.3, -8.0, 10.6), xyaxes=lookat((0.3, -8.0, 10.6), (0, -0.3, 0)))
    tv = (AT_TABLE[0] + 0.06, AT_TABLE[1] - 3.2, TABLE["h"] + 1.0)
    sub(world, "camera", name="table_view", pos=f(*tv), xyaxes=lookat(tv, (AT_TABLE[0] + 0.18, AT_TABLE[1] - 0.1, TABLE["h"] + 0.17)))

    # robot: planar chassis wrapping the vendor body tree
    chassis = sub(world, "body", name="chassis", childclass="i7")
    sub(chassis, "joint", name="base_x", type="slide", axis="1 0 0", damping="50")
    sub(chassis, "joint", name="base_y", type="slide", axis="0 1 0", damping="50")
    sub(chassis, "joint", name="base_yaw", type="hinge", axis="0 0 1", damping="50")
    base = copy.deepcopy(vendor.find("worldbody/body[@name='base_link']"))
    base.set("pos", f(BASE_TO_CENTER, 0, 0))
    for b in base.iter("body"):
        b.set("gravcomp", "1")
    base.set("gravcomp", "1")
    materials = {"base_link": "shell", "Shoulder_Base": "lilac"}
    for g in base.iter("geom"):
        mesh = g.get("mesh", "")
        g.attrib.pop("rgba", None)
        g.set("material", materials.get(mesh, "flange" if mesh.startswith("falan") else "graphite" if mesh.startswith("Gripper") else "shell"))
    lift = base.find("body[@name='Shoulder_Base']")
    # head camera on the lift mast, looking forward and 35 degrees down
    sub(lift, "camera", name="head_cam", pos="0.07 0 0.3", xyaxes="0 -1 0 0.574 0 0.819", fovy="62")
    chassis.append(base)

    # the bottle comes after the robot so the keyframe qpos order is robot first, bottle last
    bottle = sub(world, "body", name="bottle", pos=f(BOTTLE[0], BOTTLE[1], TABLE["h"] + 0.1075))
    sub(bottle, "freejoint", name="bottle")
    sub(bottle, "geom", name="bottle_body", type="cylinder", size="0.033 0.1075", mass="0.55", material="bottle")
    sub(bottle, "geom", name="bottle_cap", type="cylinder", size="0.0155 0.01", pos="0 0 0.1175", mass="0.005", material="cap")

    act = sub(root, "actuator")
    for joint, kv in [("base_x", 400), ("base_y", 400), ("base_yaw", 300)]:
        sub(act, "velocity", name=f"vel_{joint}", joint=joint, kv=kv, ctrlrange="-0.5 0.5" if joint != "base_yaw" else "-1 1")
    for m in vendor.find("actuator"):
        act.append(copy.deepcopy(m))

    # keyframes: chassis (3) + lift (1) + 14 arm joints + bottle free joint (7)
    rest_r = [0.12, -0.08, 0, -0.28, 0, 0, 0.1]
    rest_l = [0.12, 0.08, 0, -0.28, 0, 0, 0.1]
    bottle_q = [BOTTLE[0], BOTTLE[1], TABLE["h"] + 0.1075, 1, 0, 0, 0]
    keys = sub(root, "keyframe")
    for name, (x, y, yaw), lift_q in [("start", START, 0.0), ("at_table", AT_TABLE, LIFT_AT_TABLE)]:
        q = [x, y, yaw, lift_q] + rest_r + rest_l + bottle_q
        sub(keys, "key", name=name, qpos=f(*[float(v) for v in q]))

    ET.indent(root, space="  ")
    out = HERE / "i7_lab.xml"
    ET.ElementTree(root).write(out, encoding="utf-8", xml_declaration=False)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
